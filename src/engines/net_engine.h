/* ?????? Initialize net engine ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void net_init(void) {
    if(!g_netCSInit) { InitializeCriticalSection(&g_netCS); g_netCSInit=TRUE; }
    /* Pre-load blocklist */
    for(int i=0; g_dnsMalicious[i] && g_blockedDomainCnt<NET_MAX_BLOCK; i++) {
        strncpy(g_blockedDomains[g_blockedDomainCnt].entry, g_dnsMalicious[i], 255);
        strncpy(g_blockedDomains[g_blockedDomainCnt].reason, "Known malicious", 63);
        g_blockedDomainCnt++;
    }
}

/* ?????? Get process name by PID ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void net_get_procname(DWORD pid, char *out, int outLen) {
    HANDLE h = CreateToolhelp32Snapshot(TH32CS_SNAPPROCESS, 0);
    if(h == INVALID_HANDLE_VALUE) { strncpy(out,"<unknown>",outLen-1); return; }
    PROCESSENTRY32 pe; pe.dwSize = sizeof(pe);
    if(Process32First(h, &pe)) {
        do {
            if(pe.th32ProcessID == pid) {
                strncpy(out, pe.szExeFile, outLen-1);
                CloseHandle(h); return;
            }
        } while(Process32Next(h, &pe));
    }
    CloseHandle(h);
    strncpy(out, "<unknown>", outLen-1);
}

/* ?????? Addr to string ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void net_addr_str(DWORD addr, USHORT port, char *out, int outLen) {
    struct in_addr ia; ia.s_addr = addr;
    snprintf(out, outLen, "%s:%u", inet_ntoa(ia), ntohs(port));
}

/* ?????? Check if IP is suspicious ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL net_is_suspicious_ip(const char *ip) {
    for(int i=0; g_maliciousIPs[i]; i++)
        if(strncmp(ip, g_maliciousIPs[i], strlen(g_maliciousIPs[i]))==0) return TRUE;
    /* Private/loopback are safe */
    if(strncmp(ip,"127.",4)==0||strncmp(ip,"10.",3)==0||
       strncmp(ip,"192.168.",8)==0||strncmp(ip,"172.",4)==0||
       strcmp(ip,"0.0.0.0")==0) return FALSE;
    return FALSE;
}

/* ?????? Classify connection endpoint & reverse DNS ?????????????????????????????????????????????????????????????????????????????????????????? */
/* ?????? Classify connection endpoint (Instant, non-blocking) ??????????????????????????????????????????????????? */
static void net_classify_endpoint(NetConn *c, DWORD remoteAddr, USHORT remotePort) {
    struct in_addr ia; ia.s_addr = remoteAddr;
    char *ipStr = inet_ntoa(ia);
    USHORT rPort = ntohs(remotePort);

    /* Local / loopback / LAN */
    if (strncmp(ipStr, "127.", 4) == 0 || strcmp(ipStr, "0.0.0.0") == 0) {
        strcpy(c->category, "Loopback");
        strcpy(c->remoteHost, "localhost");
        return;
    }
    if (strncmp(ipStr, "192.168.", 8) == 0 || strncmp(ipStr, "10.", 3) == 0 ||
        (strncmp(ipStr, "172.", 4) == 0 && atoi(ipStr + 4) >= 16 && atoi(ipStr + 4) <= 31)) {
        strcpy(c->category, "LAN / Local");
        strcpy(c->remoteHost, "local.network");
        return;
    }

    /* Process-based classification */
    char loProc[64] = {0};
    for(int i = 0; c->procName[i] && i < 63; i++) loProc[i] = (char)tolower((unsigned char)c->procName[i]);

    if (strstr(loProc, "steam") || strstr(loProc, "epic") || strstr(loProc, "download") || strstr(loProc, "update")) {
        strcpy(c->category, "Download / Web");
        strcpy(c->remoteHost, "Content Delivery Network (CDN)");
        return;
    }

    if (strstr(loProc, "msedge") || strstr(loProc, "chrome") || strstr(loProc, "firefox") || strstr(loProc, "brave") || strstr(loProc, "opera")) {
        strcpy(c->category, "Web / Cloud");
        strcpy(c->remoteHost, (rPort == 443) ? "Encrypted TLS Web Host" : "HTTP Web Host");
        return;
    }

    /* Standard Web / Cloud ports */
    if (rPort == 80 || rPort == 443 || rPort == 8080 || rPort == 8443) {
        strcpy(c->category, "Web / Cloud");
        strcpy(c->remoteHost, (rPort == 443 || rPort == 8443) ? "Cloud Edge / HTTPS" : "Web Service / HTTP");
        return;
    }

    /* Unverified bare IP on non-standard port */
    strcpy(c->category, "Unverified IP");
    snprintf(c->remoteHost, sizeof(c->remoteHost), "Raw Socket [%s]", ipStr);
    c->suspicious = TRUE;
    c->beaconScore = 65;
}

/* ?????? Scan TCP connections ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static int net_scan_connections(void) {
    DWORD sz = 0;
    GetExtendedTcpTable(NULL,&sz,FALSE,AF_INET,TCP_TABLE_OWNER_PID_ALL,0);
    MIB_TCPTABLE_OWNER_PID *tbl = (MIB_TCPTABLE_OWNER_PID*)LocalAlloc(LMEM_FIXED,sz);
    if(!tbl) return 0;
    if(GetExtendedTcpTable(tbl,&sz,FALSE,AF_INET,TCP_TABLE_OWNER_PID_ALL,0)!=NO_ERROR){
        LocalFree(tbl); return 0;
    }

    EnterCriticalSection(&g_netCS);
    g_netConnCnt = 0;
    static const char *states[]={"","CLOSED","LISTEN","SYN_SENT","SYN_RCVD",
        "ESTABLISHED","FIN_WAIT1","FIN_WAIT2","CLOSE_WAIT","CLOSING","LAST_ACK",
        "TIME_WAIT","DELETE_TCB"};

    for(DWORD i=0; i<tbl->dwNumEntries && g_netConnCnt<NET_MAX_CONN; i++) {
        MIB_TCPROW_OWNER_PID *r = &tbl->table[i];
        NetConn *c = &g_netConns[g_netConnCnt++];
        ZeroMemory(c, sizeof(*c));
        c->pid       = r->dwOwningPid;
        c->localPort = (USHORT)r->dwLocalPort;
        c->remotePort= (USHORT)r->dwRemotePort;
        c->firstSeen = time(NULL);

        net_get_procname(r->dwOwningPid, c->procName, sizeof(c->procName));

        char la[48],ra[48];
        net_addr_str(r->dwLocalAddr, r->dwLocalPort, la, sizeof(la));
        net_addr_str(r->dwRemoteAddr, r->dwRemotePort, ra, sizeof(ra));
        strncpy(c->localAddr, la, 47);
        strncpy(c->remoteAddr, ra, 47);

        DWORD st = r->dwState;
        strncpy(c->state, (st<13)?states[st]:"UNKNOWN", 23);

        /* Classify endpoint & DNS */
        net_classify_endpoint(c, r->dwRemoteAddr, r->dwRemotePort);
    }
    LeaveCriticalSection(&g_netCS);
    LocalFree(tbl);
    return g_netConnCnt;
}

/* ?????? Run baseline startup scan & report ??????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void net_run_baseline_scan(NetBaselineReport *rep) {
    net_scan_connections();
    ZeroMemory(rep, sizeof(*rep));
    rep->totalConns = g_netConnCnt;

    for(int i = 0; i < g_netConnCnt; i++) {
        if(strcmp(g_netConns[i].category, "Web / Cloud") == 0) rep->webConns++;
        else if(strcmp(g_netConns[i].category, "Download / Web") == 0) rep->downloadConns++;
        else if(strstr(g_netConns[i].category, "LAN") || strstr(g_netConns[i].category, "Loopback")) rep->lanConns++;
        else {
            rep->unverifiedConns++;
            if(rep->unverifiedConns <= 32) {
                int idx = rep->unverifiedConns - 1;
                rep->unverifiedPids[idx] = g_netConns[i].pid;
                strncpy(rep->unverifiedProcs[idx], g_netConns[i].procName, 63);
                snprintf(rep->unverifiedAddrs[idx], 63, "%s -> %s", g_netConns[i].procName, g_netConns[i].remoteAddr);
            }
        }
    }
    g_lastBaseline = *rep;
}



/* ?????? Scan open listening ports ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
typedef struct { USHORT port; char procName[64]; DWORD pid; } OpenPort;
static OpenPort g_openPorts[512];
static int      g_openPortCnt = 0;

static int net_scan_open_ports(void) {
    DWORD sz = 0;
    GetExtendedTcpTable(NULL,&sz,FALSE,AF_INET,TCP_TABLE_OWNER_PID_ALL,0);
    MIB_TCPTABLE_OWNER_PID *tbl=(MIB_TCPTABLE_OWNER_PID*)LocalAlloc(LMEM_FIXED,sz);
    if(!tbl) return 0;
    GetExtendedTcpTable(tbl,&sz,FALSE,AF_INET,TCP_TABLE_OWNER_PID_ALL,0);
    g_openPortCnt=0;
    for(DWORD i=0; i<tbl->dwNumEntries && g_openPortCnt<512; i++) {
        if(tbl->table[i].dwState==MIB_TCP_STATE_LISTEN) {
            OpenPort *p=&g_openPorts[g_openPortCnt++];
            p->port=ntohs((USHORT)tbl->table[i].dwLocalPort);
            p->pid=tbl->table[i].dwOwningPid;
            net_get_procname(p->pid,p->procName,sizeof(p->procName));
        }
    }
    LocalFree(tbl);
    return g_openPortCnt;
}

/* ?????? DNS Protection: add domain to hosts file ????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL net_block_domain(const char *domain) {
    char hostsPath[MAX_PATH];
    ExpandEnvironmentStringsA("%SystemRoot%\\System32\\drivers\\etc\\hosts",
                              hostsPath,sizeof(hostsPath));
    /* Check if already blocked */
    FILE *f=fopen(hostsPath,"r");
    if(f){ char line[512];
        while(fgets(line,sizeof(line),f)){
            if(strstr(line,domain)){fclose(f);return TRUE;}
        } fclose(f); }
    /* Append block entry */
    f=fopen(hostsPath,"a");
    if(!f) return FALSE;
    fprintf(f,"0.0.0.0 %s # Kaevex DNS Block\n",domain);
    fclose(f);
    /* Flush DNS cache */
    ShellExecuteA(NULL,"runas","ipconfig","/flushdns",NULL,SW_HIDE);
    return TRUE;
}

/* ?????? Close port via firewall ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void net_close_port(USHORT port, const char *proto) {
    char args[512];
    snprintf(args,sizeof(args),
        "advfirewall firewall add rule name=\"Kaevex-ClosePort-%u\" "
        "dir=in action=block protocol=%s localport=%u enable=yes",
        port,proto,port);
    SHELLEXECUTEINFOA sei={0}; sei.cbSize=sizeof(sei);
    sei.lpVerb="runas"; sei.lpFile="netsh";
    sei.lpParameters=args; sei.fMask=SEE_MASK_NOCLOSEPROCESS|SEE_MASK_NO_CONSOLE;
    sei.nShow=SW_HIDE;
    if(ShellExecuteExA(&sei)&&sei.hProcess){
        WaitForSingleObject(sei.hProcess,5000); CloseHandle(sei.hProcess);
    }
}

/* ?????? Kill suspicious connection (terminate owning process) ?????????????????????????????????????????????????????? */
static BOOL net_kill_connection_pid(DWORD pid) {
    HANDLE hp=OpenProcess(PROCESS_TERMINATE,FALSE,pid);
    if(!hp) return FALSE;
    BOOL r=TerminateProcess(hp,1);
    CloseHandle(hp); return r;
}

/* ?????? Get network stats ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
typedef struct { long long bytesSent; long long bytesRecv; int activeConns; int suspConn; } NetStats;
static void net_get_stats(NetStats *s) {
    ZeroMemory(s,sizeof(*s));
    MIB_IFTABLE *tbl=NULL; DWORD sz=0;
    GetIfTable(NULL,&sz,FALSE);
    tbl=(MIB_IFTABLE*)LocalAlloc(LMEM_FIXED,sz);
    if(tbl&&GetIfTable(tbl,&sz,FALSE)==NO_ERROR){
        for(DWORD i=0;i<tbl->dwNumEntries;i++){
            s->bytesSent+=(long long)tbl->table[i].dwOutOctets;
            s->bytesRecv+=(long long)tbl->table[i].dwInOctets;
        }
        LocalFree(tbl);
    }
    s->activeConns=g_netConnCnt;
    for(int i=0;i<g_netConnCnt;i++) if(g_netConns[i].suspicious) s->suspConn++;
}

