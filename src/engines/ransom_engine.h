/* ?????? Check if extension looks encrypted ???????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL rw_is_encrypted_ext(const char *path) {
    const char *ext = strrchr(path, '.');
    if(!ext) return FALSE;
    for(int i=0; g_encryptedExt[i]; i++)
        if(_stricmp(ext, g_encryptedExt[i])==0) return TRUE;
    return FALSE;
}

static BOOL rw_is_target_ext(const char *path) {
    const char *ext = strrchr(path, '.');
    if(!ext) return FALSE;
    for(int i=0; g_targetExt[i]; i++)
        if(_stricmp(ext, g_targetExt[i])==0) return TRUE;
    return FALSE;
}

/* ?????? Add event ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void rw_add_event(const char *path, const char *action, BOOL suspicious) {
    EnterCriticalSection(&g_rwCS);
    if(g_rwEvtCnt < RW_MAX_EVENTS) {
        RwEvent *e = &g_rwEvents[g_rwEvtCnt++];
        strncpy(e->path, path, MAX_PATH-1);
        strncpy(e->action, action, 23);
        e->when = time(NULL);
        e->suspicious = suspicious;
    } else {
        /* Ring: drop oldest */
        memmove(g_rwEvents, g_rwEvents+1, (RW_MAX_EVENTS-1)*sizeof(RwEvent));
        RwEvent *e = &g_rwEvents[RW_MAX_EVENTS-1];
        strncpy(e->path, path, MAX_PATH-1);
        strncpy(e->action, action, 23);
        e->when = time(NULL);
        e->suspicious = suspicious;
    }
    LeaveCriticalSection(&g_rwCS);
}

/* ?????? Create VSS snapshot via vssadmin ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL rw_create_vss_snapshot(const char *drive, char *shadowPathOut, int outLen) {
    char cmd[256];
    snprintf(cmd, sizeof(cmd), "create shadow /for=%c:", drive[0]);
    char args[512];
    snprintf(args, sizeof(args), "/c vssadmin %s > \"%s\\aegis_vss.log\" 2>&1",
             cmd, getenv("TEMP")?getenv("TEMP"):"C:\\Temp");

    SHELLEXECUTEINFOA sei={0}; sei.cbSize=sizeof(sei);
    sei.lpVerb="runas"; sei.lpFile="cmd.exe";
    sei.lpParameters=args;
    sei.fMask=SEE_MASK_NOCLOSEPROCESS|SEE_MASK_NO_CONSOLE;
    sei.nShow=SW_HIDE;
    if(!ShellExecuteExA(&sei)) return FALSE;
    WaitForSingleObject(sei.hProcess, 15000);
    CloseHandle(sei.hProcess);

    /* Read log to find shadow path */
    char logPath[MAX_PATH];
    snprintf(logPath,sizeof(logPath),"%s\\aegis_vss.log",
             getenv("TEMP")?getenv("TEMP"):"C:\\Temp");
    FILE *f=fopen(logPath,"r");
    if(!f) return FALSE;
    char line[512];
    BOOL found=FALSE;
    while(fgets(line,sizeof(line),f)){
        char *p=strstr(line,"\\\\?\\GLOBALROOT\\Device\\HarddiskVolumeShadowCopy");
        if(p){ strncpy(shadowPathOut,p,outLen-1); found=TRUE; break; }
    }
    fclose(f);
    DeleteFileA(logPath);
    return found;
}

/* ?????? Deploy honeypot decoy files ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static int rw_deploy_honeypots(const char *dir) {
    g_honeyCnt = 0;
    /* Common ransomware target locations */
    const char *locs[3];
    char docs[MAX_PATH], desk[MAX_PATH];
    SHGetFolderPathA(NULL, CSIDL_PERSONAL,  NULL, 0, docs);
    SHGetFolderPathA(NULL, CSIDL_DESKTOPDIRECTORY, NULL, 0, desk);
    locs[0]=docs; locs[1]=desk; locs[2]=dir;

    for(int l=0; l<3 && g_honeyCnt<RW_MAX_HONEY; l++) {
        if(!locs[l]||!locs[l][0]) continue;
        for(int i=0; i<2 && g_honeyCnt<RW_MAX_HONEY; i++) {
            HoneyFile *hf = &g_honey[g_honeyCnt];
            snprintf(hf->path, MAX_PATH-1, "%s\\~KaevexDecoy_%02d.docx", locs[l], i);
            /* Never overwrite user data if a canary filename already exists. */
            HANDLE f=CreateFileA(hf->path,GENERIC_WRITE,0,NULL,CREATE_NEW,FILE_ATTRIBUTE_NORMAL,NULL);
            if(f!=INVALID_HANDLE_VALUE){
                char content[192]; DWORD written=0;
                int contentLen=snprintf(content,sizeof(content),
                    "Kaevex ransomware canary file. Access or modification is monitored.\r\nID:%08lX\r\n",
                    (unsigned long)(GetTickCount()+l*100+i));
                BOOL wrote=WriteFile(f,content,(DWORD)contentLen,&written,NULL) && written==(DWORD)contentLen;
                CloseHandle(f);
                if(!wrote){ DeleteFileA(hf->path); continue; }
                hf->touched=FALSE;
                WIN32_FILE_ATTRIBUTE_DATA baseData={0};
                if(GetFileAttributesExA(hf->path,GetFileExInfoStandard,&baseData))
                    hf->baselineWriteTime=baseData.ftLastWriteTime;
                else
                    ZeroMemory(&hf->baselineWriteTime,sizeof(hf->baselineWriteTime));
                g_honeyCnt++;
            }
        }
    }
    return g_honeyCnt;
}

