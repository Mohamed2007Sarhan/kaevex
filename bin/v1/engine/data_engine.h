/* ?????? Init ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void dg_init(void) {
    if(!g_dgCSInit){ InitializeCriticalSection(&g_dgCS); g_dgCSInit=TRUE; }
}

/* ?????? Should scan this file ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL dg_should_scan(const char *path) {
    const char *ext=strrchr(path,'.');
    if(!ext) return FALSE;
    for(int i=0; g_dgScanExt[i]; i++)
        if(_stricmp(ext,g_dgScanExt[i])==0) return TRUE;
    return FALSE;
}

/* ?????? Redact a line for display ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static void dg_redact(const char *line, char *out, int outLen) {
    strncpy(out,line,outLen-1);
    /* Replace middle chars of long values with *** */
    char *eq=strrchr(out,'=');
    if(!eq) eq=strrchr(out,':');
    if(eq && strlen(eq)>8) {
        int vlen=(int)strlen(eq);
        int keep=3;
        for(int i=keep+1;i<vlen-keep-1&&i<outLen-4;i++) eq[i]='*';
    }
}

/* ?????? Scan a single file ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static int dg_scan_file(const char *path) {
    FILE *f=fopen(path,"r"); if(!f) return 0;
    /* Skip files > DG_MAX_SCAN_MB */
    fseek(f,0,SEEK_END); long sz=ftell(f); rewind(f);
    if(sz > (long)DG_MAX_SCAN_MB*1024*1024){ fclose(f); return 0; }

    char line[4096]; int lineNo=0, found=0;
    while(fgets(line,sizeof(line),f) && g_dgFindingCnt<DG_MAX_FINDINGS) {
        lineNo++;
        char lo[4096]={0};
        int n=(int)strlen(line); if(n>4095)n=4095;
        for(int i=0;i<n;i++) lo[i]=(char)tolower((unsigned char)line[i]);

        for(int p=0; g_dgPatterns[p].name; p++) {
            char patLo[128]={0};
            strncpy(patLo,g_dgPatterns[p].pattern,127);
            for(int i=0;patLo[i];i++) patLo[i]=(char)tolower((unsigned char)patLo[i]);

            if(strstr(lo,patLo)) {
                EnterCriticalSection(&g_dgCS);
                DgFinding *fnd=&g_dgFindings[g_dgFindingCnt++];
                strncpy(fnd->file,path,MAX_PATH-1);
                fnd->type=g_dgPatterns[p].type;
                fnd->typeName=g_dgPatterns[p].name;
                fnd->line=lineNo;
                strncpy(fnd->severity,g_dgPatterns[p].severity,15);
                fnd->found=time(NULL);
                dg_redact(line,fnd->snippet,sizeof(fnd->snippet));
                /* trim trailing newline */
                int sl=(int)strlen(fnd->snippet);
                while(sl>0&&(fnd->snippet[sl-1]=='\n'||fnd->snippet[sl-1]=='\r')) fnd->snippet[--sl]='\0';
                LeaveCriticalSection(&g_dgCS);
                found++;
                break; /* one pattern per line enough */
            }
        }
    }
    fclose(f);
    return found;
}

/* ?????? Recursive directory scan ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static int dg_scan_dir(const char *dir, int depth) {
    if(depth>5||g_dgFindingCnt>=DG_MAX_FINDINGS) return 0;
    int total=0;
    char pat[MAX_PATH]; snprintf(pat,sizeof(pat),"%s\\*",dir);
    WIN32_FIND_DATAA fd; HANDLE h=FindFirstFileA(pat,&fd);
    if(h==INVALID_HANDLE_VALUE) return 0;
    do {
        if(strcmp(fd.cFileName,".")==0||strcmp(fd.cFileName,"..")==0) continue;
        char full[MAX_PATH]; snprintf(full,sizeof(full),"%s\\%s",dir,fd.cFileName);
        if(fd.dwFileAttributes&FILE_ATTRIBUTE_DIRECTORY) {
            /* Skip system dirs */
            if(_stricmp(fd.cFileName,"Windows")==0||
               _stricmp(fd.cFileName,"Program Files")==0||
               _stricmp(fd.cFileName,"ProgramData")==0||
               _stricmp(fd.cFileName,".git")==0||
               _stricmp(fd.cFileName,"node_modules")==0) continue;
            total+=dg_scan_dir(full,depth+1);
        } else if(dg_should_scan(full)) {
            total+=dg_scan_file(full);
        }
    } while(FindNextFileA(h,&fd)&&g_dgFindingCnt<DG_MAX_FINDINGS);
    FindClose(h);
    return total;
}

/* ?????? Luhn check for credit cards ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL dg_luhn_check(const char *num) {
    int sum=0,n=(int)strlen(num),alt=0;
    for(int i=n-1;i>=0;i--){
        if(!isdigit((unsigned char)num[i])) return FALSE;
        int d=num[i]-'0';
        if(alt){ d*=2; if(d>9) d-=9; }
        sum+=d; alt=!alt;
    }
    return (sum%10==0);
}

/* ?????? Check clipboard for sensitive data ???????????????????????????????????????????????????????????????????????????????????????????????????????????? */
static BOOL dg_check_clipboard(char *alertMsg, int msgLen) {
    if(!OpenClipboard(NULL)) return FALSE;
    HANDLE h=GetClipboardData(CF_TEXT);
    if(!h){CloseClipboard();return FALSE;}
    char *txt=(char*)GlobalLock(h);
    if(!txt){CloseClipboard();return FALSE;}
    char lo[8192]={0}; int n=CLAMP((int)strlen(txt),0,8191);
    for(int i=0;i<n;i++) lo[i]=(char)tolower((unsigned char)txt[i]);
    GlobalUnlock(h); CloseClipboard();

    for(int p=0; g_dgPatterns[p].name; p++) {
        char patLo[128]={0}; strncpy(patLo,g_dgPatterns[p].pattern,127);
        for(int i=0;patLo[i];i++) patLo[i]=(char)tolower((unsigned char)patLo[i]);
        if(strstr(lo,patLo)&&strcmp(lo,g_dgClipLast)!=0) {
            strncpy(g_dgClipLast,lo,8191);
            snprintf(alertMsg,msgLen,"CLIPBOARD: %s detected in clipboard!",g_dgPatterns[p].name);
            g_dgClipAlert=TRUE;
            return TRUE;
        }
    }
    return FALSE;
}

